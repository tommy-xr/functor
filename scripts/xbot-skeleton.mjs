// Generate examples/fullbody/skeleton.fun: Xbot's bind skeleton as plain data.
//
// The glTF nests the skin under a node scaled 0.01 (centimetres to metres).
// `Model.skinned` joints have unit scale, so every translation is multiplied
// by its ancestors' (uniform) scale; rotations and model-space positions are
// unchanged. `bind` is each joint's model-space bind position and rotation.
//
// Usage: node scripts/xbot-skeleton.mjs   (after `npm run fetch:assets`)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const GLB = `${ROOT}examples/fullbody/Xbot.glb`;
const OUT = `${ROOT}examples/fullbody/skeleton.fun`;

const glb = readFileSync(GLB);
const json = JSON.parse(glb.subarray(20, 20 + glb.readUInt32LE(12)).toString("utf8"));
const nodes = json.nodes;
const skin = new Set(json.skins[0].joints);

const parentOf = new Map();
nodes.forEach((n, i) => (n.children ?? []).forEach((c) => parentOf.set(c, i)));

// Skin joints plus their non-skin ancestors (the scaled `Xbot` node), the
// set the engine poses.
const used = new Set();
for (const j of skin) for (let i = j; i !== undefined; i = parentOf.get(i)) used.add(i);

// Parents first, children in glTF order.
const order = [];
const visit = (i) => {
  order.push(i);
  for (const c of nodes[i].children ?? []) if (used.has(c)) visit(c);
};
[...used].filter((i) => !used.has(parentOf.get(i))).forEach(visit);

const qmul = ([ax, ay, az, aw], [bx, by, bz, bw]) => [
  aw * bx + ax * bw + ay * bz - az * by,
  aw * by - ax * bz + ay * bw + az * bx,
  aw * bz + ax * by - ay * bx + az * bw,
  aw * bw - ax * bx - ay * by - az * bz,
];
const rotate = ([x, y, z, w], v) => {
  const t = [2 * (y * v[2] - z * v[1]), 2 * (z * v[0] - x * v[2]), 2 * (x * v[1] - y * v[0])];
  return [v[0] + w * t[0] + (y * t[2] - z * t[1]), v[1] + w * t[1] + (z * t[0] - x * t[2]), v[2] + w * t[2] + (x * t[1] - y * t[0])];
};

const index = new Map(order.map((n, i) => [n, i]));
const model = new Map(); // node -> { scale, position, rotation }
const rows = [];
for (const n of order) {
  const node = nodes[n];
  const s = node.scale ?? [1, 1, 1];
  if (Math.max(...s) - Math.min(...s) > 1e-5) throw new Error(`${node.name}: non-uniform scale ${s}`);
  const p = model.get(parentOf.get(n)) ?? { scale: 1, position: [0, 0, 0], rotation: [0, 0, 0, 1] };
  const t = (node.translation ?? [0, 0, 0]).map((v) => v * p.scale);
  const r = node.rotation ?? [0, 0, 0, 1];
  const position = rotate(p.rotation, t).map((v, i) => v + p.position[i]);
  const rotation = qmul(p.rotation, r);
  model.set(n, { scale: p.scale * s[0], position, rotation });
  rows.push({ name: node.name, parent: index.get(parentOf.get(n)), t, r, position, rotation });
}

const f = (v) => {
  // Sub-micron values are export noise; zeroing them also avoids exponents.
  if (Math.abs(v) < 1e-6) return "0.0";
  const s = v.toPrecision(7);
  return s.includes(".") ? s : `${s}.0`;
};
const vec = ([x, y, z]) => `Vec3.make(${f(x)}, ${f(y)}, ${f(z)})`;
const pt = ([x, y, z]) => `{ x: ${f(x)}, y: ${f(y)}, z: ${f(z)} }`;
const quat = ([x, y, z, w]) => `{ x: ${f(x)}, y: ${f(y)}, z: ${f(z)}, w: ${f(w)} }`;
const parent = (p) => (p === undefined ? "Option.None" : `Option.Some(${p}.0)`);

const out = `// GENERATED by scripts/xbot-skeleton.mjs from Xbot.glb — do not edit.
// Xbot's bind skeleton at unit scale (metres, Y up, facing +Z).

/// One joint's model-space bind position and rotation.
type Bind = { name: string, position: Input.point3, rotation: Input.quaternion }

/// The skeleton as \`Model.skinned\` joints, parents first.
let joints: List<Model.joint> = [
${rows.map((r) => `  { name: "${r.name}", parent: ${parent(r.parent)}, translation: ${vec(r.t)}, rotation: ${quat(r.r)} },`).join("\n")}
]

/// Each joint's model-space bind pose, in \`joints\` order.
let bind: List<Bind> = [
${rows.map((r) => `  { name: "${r.name}", position: ${pt(r.position)}, rotation: ${quat(r.rotation)} },`).join("\n")}
]
`;
writeFileSync(OUT, out);
console.log(`wrote ${OUT} (${rows.length} joints)`);
